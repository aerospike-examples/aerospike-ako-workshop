def targets() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for key, profile in PROFILES.items():
        suffix = "" if key == "eks" else f"-{key}"
        out[WORKSHOP_ROOT / "manifests" / f"all-flash-cluster{suffix}.yaml"] = render_manifest(profile)
        out[WORKSHOP_ROOT / "helm" / f"base-all-flash-cluster{suffix}-values.yaml"] = render_values(profile)
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero when a generated file is missing or out of date",
    )
    args = parser.parse_args()

    stale: list[Path] = []
    for path, content in targets().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                stale.append(path)
            continue
        path.write_text(content)
        print(f"wrote {path.relative_to(WORKSHOP_ROOT.parent)}")

    if stale:
        for path in stale:
            print(f"STALE {path.relative_to(WORKSHOP_ROOT.parent)}", file=sys.stderr)
        print("Run scripts/labs/render-all-flash-manifests.py to regenerate.", file=sys.stderr)
        return 1
    if args.check:
        print("all-flash manifests up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
